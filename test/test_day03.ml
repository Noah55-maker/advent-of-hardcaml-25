let simple_testbench (sim : Harness.Sim.t) =
  let inputs = Cyclesim.inputs sim in
  let outputs = Cyclesim.outputs sim in
  let cycle ?n () = Cyclesim.cycle ?n sim in
  (* Helper function for inputting one value *)
  let feed_input n =
    inputs.data_in <--. n;
    inputs.data_in_valid := Bits.vdd;
    cycle ();
    inputs.data_in_valid := Bits.gnd;
    cycle ()
  in
  (* Reset the design *)
  inputs.clear := Bits.vdd;
  cycle ();
  inputs.clear := Bits.gnd;
  cycle ();
  (* Pulse the start signal *)
  inputs.start := Bits.vdd;
  cycle ();
  inputs.start := Bits.gnd;
  (* Input some data *)
  List.iter sample_input_values ~f:(fun x -> feed_input x);
  inputs.finish := Bits.vdd;
  cycle ();
  inputs.finish := Bits.gnd;
  cycle ();

  while not (Bits.to_bool !(outputs.answer1.valid)) do
    cycle ()
  done;
  let answer1 = Bits.to_signed_int !(outputs.answer1.value) in
  let answer2 = Bits.to_signed_int !(outputs.answer2.value) in
  print_s [%message "Result" (answer1 : int) (answer2 : int)];
  cycle ~n:2 ()
;;

let waves_config = Waves_config.no_waves

let%expect_test "Simple test, optionally saving waveforms to disk" =
  Harness.run_advanced ~waves_config ~create:Day03.hierarchical simple_testbench;
  [%expect {| (Result (answer1 98) (answer2 0)) |}]
;;

